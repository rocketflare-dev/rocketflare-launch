/** The kit bootstrap against `ctx.dbUri`, then the dev-server keys. See the header. */
export async function sessionBootstrap(ctx: SessionBootstrapContext): Promise<BootstrapTimings> {
  const { sandbox, dev } = ctx
  const env = sessionProcessEnv(dev)
  let shown: string | null = null
  const show = async (detail: string) => {
    if (!ctx.onProgress || detail === shown) return
    shown = detail
    await Promise.resolve(ctx.onProgress(detail)).catch(() => {})
  }
  const progressCtx: SessionBootstrapContext = { ...ctx, onProgress: show }

  // The container reaches its database directly — so exactly that endpoint joins the allow-list,
  // REPLACING any earlier one (the `dev` a prepare run used is dropped when the session's own
  // branch takes over). A URI that is not a Neon endpoint throws here, before anything runs.
  await sandbox.setAllowedHosts(sessionAllowedHosts(sessionDbEgressHosts(ctx.dbUri)))

  const t0 = Date.now()
  const installed = ctx.install !== false
  if (installed) {
    await show(INSTALL_PROGRESS)
    await installDependencies(progressCtx)
  }

  const t1 = Date.now()
  await sandbox.writeFile(NOT_ROOT_PRELOAD, NOT_ROOT_PRELOAD_SCRIPT)
  // The database check, the kit's second install and its wrangler login check never run in a
  // sandbox: through the kit's own flags when its bootstrap takes them, else the preload's.
  const invocation = bootstrapInvocation(await checkoutTakesKitFlags(sandbox), ctx.skip)
  await show(BOOTSTRAP_PROGRESS)
  // The bootstrap prints its own `✖ n/10` line and the failing child's output under it.
  await runPhase(progressCtx, 'bootstrap', {
    command: invocation.command,
    timeoutMs: BOOTSTRAP_TIMEOUTS.bootstrapMs,
    env: { ...env, ...invocation.env, ...bootstrapKeepEnv(), LAUNCH_DB_URL: ctx.dbUri },
    what: "The app's bootstrap",
    progressOf: bootstrapProgressOf,
  })
  const t2 = Date.now()

  await writeDevVars(sandbox, `${SESSION_WORKSPACE}/apps/web/.dev.vars`, sessionDevVars(dev))
  return { installMs: t1 - t0, bootstrapMs: t2 - t1, installed }
}

/**
 * Step 1 of {@link sessionBootstrap} on its own: `pnpm install` in the checkout, as a polled
 * background command under the bootstrap lock. What a `prebuild` run installs with (issue #16) —
 * the same command, so the prebuild's `node_modules` is exactly what a session's install makes.
 */
export async function installDependencies(
  ctx: Omit<SessionBootstrapContext, 'dbUri'> & { dbUri?: string }
): Promise<void> {
  await runPhase({ ...ctx, dbUri: ctx.dbUri ?? '' }, 'install', {
    command: INSTALL_COMMAND,
    timeoutMs: BOOTSTRAP_TIMEOUTS.installMs,
    env: sessionProcessEnv(ctx.dev),
    what: 'pnpm install',
  })
}

/** The dependency lockfile a prebuild is keyed on (issue #16): pnpm's, at the checkout's root. */
export const LOCKFILE = 'pnpm-lock.yaml'

/**
 * What a checkout IS, for the prebuild (issue #16): its commit, that commit's tree, and the sha256
 * of {@link LOCKFILE} (`lockfile=` empty when there is none) — `head=<sha>`, `tree=<sha>`,
 * `lockfile=<hex>` lines.
 */
export const WORKSPACE_FACTS_COMMAND = `cd ${SESSION_WORKSPACE} && echo "head=$(git rev-parse HEAD)" && echo "tree=$(git rev-parse 'HEAD^{tree}')" && echo "lockfile=$( [ -f ${LOCKFILE} ] && sha256sum ${LOCKFILE} | cut -c1-64 )"`

export interface WorkspaceFacts {
  headSha: string
  treeSha: string
  /** Null when the checkout has no lockfile (nothing to compare: every restore installs). */
  lockfileHash: string | null
}

/** {@link WORKSPACE_FACTS_COMMAND} in `sandbox`; throws when git cannot answer. */
export async function workspaceFacts(sandbox: SandboxPort): Promise<WorkspaceFacts> {
  const result = await sandbox.exec(WORKSPACE_FACTS_COMMAND, { timeoutMs: 60_000 })
  const headSha = /head=([0-9a-f]{40,64})/.exec(result.stdout)?.[1]
  const treeSha = /tree=([0-9a-f]{40,64})/.exec(result.stdout)?.[1]
  if (result.exitCode !== 0 || !headSha || !treeSha) {
    throw new Error(`git could not read the workspace: ${tailOf(result.stderr, [], 5)}`)
  }
  return {
    headSha,
    treeSha,
    lockfileHash: /lockfile=([0-9a-f]{64})/.exec(result.stdout)?.[1] ?? null,
  }
}

/** Upsert `vars` into the dotenv file at `path` (inside the container). */
export async function writeDevVars(
  sandbox: SandboxPort,
  path: string,
  vars: Record<string, string>
): Promise<void> {
  const script = `${SESSION_LAUNCH_DIR}/dev-vars.mjs`
  await sandbox.writeFile(script, DEV_VARS_SCRIPT)
  const result = await sandbox.exec(`node ${script} ${path}`, {
    env: { LAUNCH_DEV_VARS: JSON.stringify(vars) },
  })
  if (result.exitCode !== 0) {
    throw new SessionBootstrapError('dev-vars', `Could not write ${path}: ${tailOf(result.stderr)}`)
  }
}

/** One port wait inside {@link startDevServer}: short, so an end request is seen between them. */
export const DEV_WAIT_CHUNK_MS = 20_000

export interface StartDevServerOptions {
  /** Called between wait chunks; throw from it to stop waiting (the person ended the session). */
  checkpoint?: () => Promise<void>
  /** Test hook: the wait chunk length. */
  chunkMs?: number
}

/**
 * The dev stack's readiness, as ONE wait (`waitForPort` with `followedBy`): `:8787/api/health` 2xx
 * FIRST, then a bare TCP connect to Vite's `:5173`. Never a GET of the UI's `/` while the API is
 * still booting: Vite would transform the whole UI graph on the same two vCPUs `wrangler dev` is
 * starting on (measured -30 % wall and -1.4 s CPU locally without it).
 */
export const DEV_READY_PROBE = {
  port: SESSION_API_PORT,
  path: '/api/health',
  followedBy: [{ port: SESSION_UI_PORT, tcp: true }],
} as const

/** How long the dev stack gets to answer {@link DEV_READY_PROBE}, all chunks together. */
export const DEV_READY_TIMEOUT_MS = BOOTSTRAP_TIMEOUTS.apiMs + BOOTSTRAP_TIMEOUTS.uiMs

/**
 * The dev server in the background ({@link DEV_START_COMMAND}), then the stack answering
 * ({@link DEV_READY_PROBE}, one in-container wait per chunk). Returns the process id. The wait is
 * chunked ({@link DEV_WAIT_CHUNK_MS}) with `opts.checkpoint` between chunks, and each chunk fails at
 * once when the dev server's process is gone (`DEV_PID_FILE`) — with the tail of its output
 * (`DEV_LOG_FILE`) as the reason, rather than a curl loop against nothing for minutes. Once it is
 * ready, the UI's `/` is warmed in the background ({@link DEV_WARM_COMMAND}, never waited on).
 */
export async function startDevServer(
  sandbox: SandboxPort,
  dev: SessionDevEnv,
  opts: StartDevServerOptions = {}
): Promise<{ processId: string }> {
  // The dev server runs on the session's own, git-ignored config — never on an edited tracked
  // toml. The script that writes it runs inside the dev start (`DEV_COMMAND`'s preload).
  await writeSessionWranglerScript(sandbox)
  const proc = await sandbox.startProcess(DEV_START_COMMAND, {
    cwd: SESSION_WORKSPACE,
    env: sessionProcessEnv(dev),
  })
  const chunkMs = opts.chunkMs ?? DEV_WAIT_CHUNK_MS
  const { port, path, followedBy } = DEV_READY_PROBE
  const deadline = Date.now() + DEV_READY_TIMEOUT_MS
  try {
    for (;;) {
      await opts.checkpoint?.()
      const left = deadline - Date.now()
      try {
        await sandbox.waitForPort(port, {
          path,
          followedBy,
          timeoutMs: Math.max(1000, Math.min(chunkMs, left)),
          pidFile: DEV_PID_FILE,
        })
        break
      } catch (err) {
        // Only "not yet" is retried; a dead process or a broken sandbox fails the step now.
        if (!isChunkTimeout(err)) throw err
        if (Date.now() >= deadline) {
          throw new Error(
            `port ${port}${path} (then ${followedBy.map(t => t.port).join(', ')}) did not answer within ${DEV_READY_TIMEOUT_MS / 1000} s`
          )
        }
      }
    }
  } catch (err) {
    if (!(err instanceof SandboxProcessExitedError) && !isPortTimeout(err)) throw err
    const log = await sandbox.readFile(DEV_LOG_FILE).catch(() => null)
    const reason =
      err instanceof SandboxProcessExitedError
        ? 'the dev server exited before its ports answered'
        : err instanceof Error
          ? err.message
          : String(err)
    throw new SessionBootstrapError(
      'dev',
      `The app's dev server did not come up: ${reason}${log ? `\n${tailOf(log)}` : ''}`
    )
  }
  // The preview's first paint: Vite's transform starts now, not when the browser first asks.
  await sandbox.startProcess(DEV_WARM_COMMAND, { cwd: SESSION_WORKSPACE }).catch(() => {})
  return { processId: proc.id }
}

/** The kit's own "stop this checkout's dev tree" (its supervisor owns the ports). */
export const DEV_STOP_COMMAND = 'pnpm dev:stop'

/** How long a warm resume gives the dev stack to answer before it restarts the dev server. */
export const DEV_PROBE_MS = 3_000

/** The dev stack answers now ({@link DEV_READY_PROBE}: the API's health, then Vite) — one call. */
export async function devServerAnswers(sandbox: SandboxPort): Promise<boolean> {
  try {
    await sandbox.waitForPort(DEV_READY_PROBE.port, {
      path: DEV_READY_PROBE.path,
      followedBy: DEV_READY_PROBE.followedBy,
      timeoutMs: DEV_PROBE_MS,
    })
    return true
  } catch {
    return false
  }
}

/**
 * The dev step of a WARM resume (`warm.ts`): the kept container's dev server is reused when both
 * ports still answer; otherwise whatever is left of it is stopped (`pnpm dev:stop` — a half-dead
 * tree would hold the strict ports) and it is started again.
 */
export async function resumeDevServer(
  sandbox: SandboxPort,
  dev: SessionDevEnv,
  opts: StartDevServerOptions = {}
): Promise<{ reused: boolean }> {
  if (await devServerAnswers(sandbox)) return { reused: true }
  await sandbox.exec(DEV_STOP_COMMAND, {
    cwd: SESSION_WORKSPACE,
    env: sessionProcessEnv(dev),
    timeoutMs: 60_000,
  })
  await startDevServer(sandbox, dev, opts)
  return { reused: false }
}

const isPortTimeout = (err: unknown) =>
  err instanceof Error && /^port \d+.* did not answer within/.test(err.message)

/** One wait chunk ran out (the adapter's `Port N did not answer within`, the fake's `never opened`). */
const isChunkTimeout = (err: unknown) =>
  !(err instanceof SandboxProcessExitedError) &&
  err instanceof Error &&
  err.name !== 'SessionStepTimeoutError' &&
  /did not answer within|never opened/.test(err.message)
