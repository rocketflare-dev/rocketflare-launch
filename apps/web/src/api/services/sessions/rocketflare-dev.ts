/** The preview origin's host suffix: `https://{label}.clewro.com` → `.clewro.com`. */
export function previewHostSuffix(template: string | undefined): string | null {
  if (!template) return null
  const host = template.replace(/^[a-z]+:\/\//i, '').split('/')[0] ?? ''
  const suffix = host.slice('{label}'.length).replace(/:\d+$/, '')
  return host.startsWith('{label}') && suffix.startsWith('.') ? suffix : null
}

export const INSTALL_COMMAND = 'pnpm install --frozen-lockfile --prefer-offline --reporter=silent'

/**
 * The kit's bootstrap refuses to run as root (kit 0.15: `os.userInfo().uid === 0` → exit 3), and a
 * sandbox's commands run as root — the container is the isolation boundary, not the user. This
 * preload tells the bootstrap's ONE check otherwise; everything it runs (pnpm, migrate, seed)
 * still runs as root. Kit 0.17.4 added the explicit opt-out (`ROCKETFLARE_ALLOW_ROOT=1`), which
 * {@link bootstrapInvocation} sets when the checkout's bootstrap takes it; the stand-in stays for older ones.
 *
 * **It also makes the bootstrap's database work lighter.** The kit's bootstrap has no flag to skip
 * its migrate, seed or database check, and reaches each ONLY as a `pnpm <script>` child
 * (`spawn('pnpm', ['db:migrate'])`, `['seed', …]`, `['web', 'db:check']`), which the preload
 * rewrites — the `spawn` binding the bootstrap imported is swapped through
 * `syncBuiltinESMExports`, before the bootstrap loads:
 * - For each part named in `LAUNCH_BOOTSTRAP_SKIP` (`BOOTSTRAP_SKIP_ENV`) it answers that child
 *   with a one-line `node -e` that prints what the kit's step checks for ("Migrations applied")
 *   and exits 0. `sessionBootstrap` always skips three ({@link ALWAYS_SKIPPED}): `db-check` (the
 *   branch was just made through Neon's API, and the migrator fails loudly if it cannot connect),
 *   `install` (the kit's step 2 `pnpm install --prefer-offline`, a second install right after
 *   Launch's own — the kit then only checks the exit code and that
 *   `apps/web/node_modules/.bin/wrangler` exists, which it still does) and `whoami` (step 8's
 *   `pnpm web exec wrangler whoami`: a sandbox never has a Cloudflare login, and the kit reads
 *   "logged in" only from "You are logged in with" in the output — the stand-in's
 *   "You are not authenticated" takes `--offline`'s not-logged-in branch, `[ai]` off, exactly as
 *   the real call did, without starting wrangler). Measured locally the two cost 8-12 s of the
 *   bootstrap. Verified against the kit's `scripts/bootstrap.mjs` and `parseWhoami`, identical
 *   from 0.15.0 through 0.17.3. **From kit 0.17.4 the kit leaves all of these out itself**
 *   (`--no-install`, `ROCKETFLARE_BOOTSTRAP_SKIP`, a `--offline` with no whoami —
 *   {@link bootstrapInvocation}), and the stand-ins are only the fallback for an older kit.
 * - `pnpm db:migrate` that is NOT skipped runs the kit's migrator ALONE
 *   (`pnpm web exec dotenv -e .dev.vars -- tsx scripts/migrate.ts`), without the kit's `db-roles`
 *   before and after it: the RLS role those make (the app's `<snake>_app`) is on `dev` already,
 *   held by `session_owner` WITH ADMIN (`NeonSessionDb`'s `ensureAppRole`), and its grants matter only under `TENANT_SCOPE_MODE=enforce`, which a
 *   session never runs. Each of those scripts opens its OWN database WebSocket through the
 *   container's egress interception, and on real Cloudflare containers one of the later ones
 *   hung (docs/plans/sandbox-session-issues.md): a prepare now opens two (migrate, seed), a
 *   session whose migrations changed one, and a resume none.
 *
 * **It keeps the bootstrap off the app's tracked files.** `--offline` makes the kit comment the
 * `[ai]` block out of BOTH wrangler tomls in place (`setAiBlocks` → `writeFileSync`), and a
 * checkpoint commits the whole tree — so the toggle once rode a session's PR, which would have
 * removed Workers AI from the app's production. Every path in `LAUNCH_BOOTSTRAP_KEEP`
 * (`BOOTSTRAP_KEEP_ENV`, absolute, comma-separated — `SESSION_DEV_TRACKED_FILES`) is written by no
 * `writeFileSync` of the bootstrap's: the call returns without writing. The session's dev server
 * runs from its own git-ignored copy instead (`SESSION_WRANGLER_SCRIPT`, run by the dev start).
 *
 * Everything else (`.dev.vars`, the install) runs as the kit wrote it.
 */
export const NOT_ROOT_PRELOAD = `${SESSION_LAUNCH_DIR}/bootstrap-in-sandbox.mjs`
export const NOT_ROOT_PRELOAD_SCRIPT = `import cp from 'node:child_process'
import fs from 'node:fs'
import { syncBuiltinESMExports } from 'node:module'
import os from 'node:os'
import path from 'node:path'
const userInfo = os.userInfo
os.userInfo = options => ({ ...userInfo(options), uid: 1000 })
const skip = new Set((process.env.LAUNCH_BOOTSTRAP_SKIP || '').split(',').filter(Boolean))
const stand = [
  ['install', a => a[0] === 'install', 'Already up to date (install skipped by Launch: it ran just before the bootstrap)'],
  ['whoami', a => a[0] === 'web' && a[1] === 'exec' && a[2] === 'wrangler' && a[3] === 'whoami', 'You are not authenticated. Please run wrangler login. (whoami skipped by Launch: a sandbox has no Cloudflare login)'],
  ['seed', a => a[0] === 'seed', 'seed skipped by Launch: a resume never re-seeds'],
  ['migrate', a => a[0] === 'db:migrate', 'Migrations applied (skipped by Launch: unchanged since the last bootstrap)'],
  ['db-check', a => a[0] === 'web' && a[1] === 'db:check', 'db:check skipped by Launch: the branch was made through the Neon API'],
]
const instead = {
  'db:migrate': ['web', 'exec', 'dotenv', '-e', '.dev.vars', '--', 'tsx', 'scripts/migrate.ts'],
}
const keep = new Set((process.env.LAUNCH_BOOTSTRAP_KEEP || '').split(',').filter(Boolean).map(f => path.resolve(f)))
const writeFileSync = fs.writeFileSync
fs.writeFileSync = function (file, ...rest) {
  if (typeof file === 'string' && keep.has(path.resolve(file))) return
  return writeFileSync.call(this, file, ...rest)
}
const spawn = cp.spawn
cp.spawn = function (cmd, args, opts) {
  const list = Array.isArray(args) ? args : []
  const hit = cmd === 'pnpm' ? stand.find(([part, match]) => skip.has(part) && match(list)) : undefined
  if (hit) {
    return spawn.call(this, process.execPath, ['-e', 'console.log(' + JSON.stringify(hit[2]) + ')'], opts)
  }
  const script = cmd === 'pnpm' ? list[0] : undefined
  if (script && Object.hasOwn(instead, script)) {
    return spawn.call(this, cmd, [...instead[script], ...list.slice(1)], opts)
  }
  return spawn.apply(this, arguments)
}
syncBuiltinESMExports()
`

