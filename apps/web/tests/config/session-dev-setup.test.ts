/**
 * A coding session's dev setup never changes a tracked file (the hola-world PR #2 bug: the kit's
 * `bootstrap --offline` commented `[ai]` out of both wrangler tomls in place, the typecheck
 * regenerated `worker-configuration.d.ts` without `AI`, and the checkpoint committed all three).
 * The scripts run for REAL here — Node, bash and git in scratch repositories — the way the
 * container runs them:
 *
 * - the bootstrap preload drops the kit bootstrap's writes to the tracked files;
 * - the session's own wrangler config is the tracked toml with `[ai]` off (the kit's own toggle,
 *   byte for byte), git-ignored, and wrangler's redirect points `wrangler dev` at it;
 * - a resume puts back what an earlier Launch committed (against the session's base);
 * - the checkpoint's guard refuses the toggle in staged content.
 *
 * Plus the `FakeSandbox` side: the bootstrap is told which files to keep, and the dev server
 * starts only after its config is written.
 */
