#!/usr/bin/env node
/**
 * Writes `apps/web/src/api/preview/capture-lib.generated.ts`: the browser build of
 * `modern-screenshot` (its UMD `dist/index.js`, which sets `window.modernScreenshot`) as one string,
 * so the Worker can serve it to the preview at `/__launch/capture.js` with no bundler loader rule —
 * the preview bridge loads it only when the person presses the camera. Run after bumping the
 * package; `tests/config/preview-capture-lib.test.ts` fails while the file and the package differ.
 *
 *   node scripts/preview-capture-lib.mjs [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const web = join(root, 'apps/web')
const require = createRequire(join(web, 'package.json'))
const pkgDir = dirname(require.resolve('modern-screenshot/package.json'))
const { version } = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'))
const source = readFileSync(join(pkgDir, 'dist/index.js'), 'utf8')

export function render(version, source) {
  return `// Generated by scripts/preview-capture-lib.mjs from modern-screenshot ${version} (MIT). Do not edit.
/** The package version the string below is. */
export const CAPTURE_LIB_VERSION = ${JSON.stringify(version)}
/** \`modern-screenshot/dist/index.js\`: a UMD build that sets \`window.modernScreenshot\`. */
export const CAPTURE_LIB_SOURCE = ${JSON.stringify(source)}
`
}

const out = join(web, 'src/api/preview/capture-lib.generated.ts')
const next = render(version, source)
if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8')
  if (current !== next) {
    console.error(`${out} is stale: run node scripts/preview-capture-lib.mjs`)
    process.exit(1)
  }
} else {
  writeFileSync(out, next)
  console.log(`wrote ${out} (modern-screenshot ${version}, ${source.length} chars)`)
}
