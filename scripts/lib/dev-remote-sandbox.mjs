/**
 * `SESSION_SANDBOX_HOST=remote` for `pnpm dev` (Launch P3, docs/SESSIONS-LOCAL.md § Real containers
 * from a laptop): local Launch drives REAL Cloudflare containers in the deployed sandbox host
 * Worker (`apps/web/wrangler.sandbox-host.toml`, `launch-sandbox-dev`) through a REMOTE service
 * binding, `SANDBOX_HOST`.
 *
 * That binding must not be in `wrangler.toml` or `wrangler.staging.toml`: a deploy of either would
 * bind production Launch to a development Worker (and fail wherever it does not exist), and the two
 * files must keep one shape (the parity test). So `apps/web/scripts/dev-server.mjs` GENERATES a
 * third file when `.dev.vars` asks for it: `wrangler.toml` byte for byte, plus the `[[services]]`
 * block, written next to it (wrangler resolves `main`, `[assets]`, the container image and
 * `.dev.vars` relative to the config file) and git-ignored. Regenerated on every start, so it can
 * never drift from `wrangler.toml`.
 *
 * `wrangler dev` then also runs with `--enable-containers=false`: the in-process `SessionSandbox`
 * is never started in this mode, so there is no image to build on the laptop.
 */

/** The generated config, in `apps/web/`. */
export const REMOTE_DEV_CONFIG = 'wrangler.dev-remote.toml'

/** The sandbox host Worker's name (`wrangler.sandbox-host.toml`). */
export const SANDBOX_HOST_SERVICE = 'launch-sandbox-dev'

/** Does `.dev.vars` (parsed) put session containers on the sandbox host? */
export function remoteSandboxEnabled(devVars = {}) {
  return String(devVars.SESSION_SANDBOX_HOST ?? '').trim() === 'remote'
}

/** `wrangler.toml`'s text with the remote binding appended, and a header saying what it is. */
export function remoteDevConfigText(baseToml) {
  return [
    '# GENERATED by apps/web/scripts/dev-server.mjs because .dev.vars says',
    '# SESSION_SANDBOX_HOST=remote — wrangler.toml plus the SANDBOX_HOST remote service binding at',
    '# the end. Do not edit (it is rewritten on every `pnpm dev`) and never deploy it. Git-ignored.',
    '',
    baseToml.trimEnd(),
    '',
    '# ---- development only: the sandbox host (docs/SESSIONS-LOCAL.md § Real containers from a laptop)',
    '[[services]]',
    'binding = "SANDBOX_HOST"',
    `service = "${SANDBOX_HOST_SERVICE}"`,
    'remote = true',
    '',
  ].join('\n')
}

/** The extra `wrangler dev` arguments for this mode. */
export function remoteDevWranglerArgs() {
  return ['-c', REMOTE_DEV_CONFIG, '--enable-containers=false']
}
