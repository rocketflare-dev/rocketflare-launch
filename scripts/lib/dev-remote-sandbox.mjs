/**
 * Both session sandbox hosts for `pnpm dev` (Launch P3, docs/SESSIONS-LOCAL.md § Real containers
 * from a laptop). Where a session's container runs is a PLATFORM SETTING
 * (`launch_settings.session_sandbox_host`, Settings → Coding agents → Session sandbox),
 * so `apps/web/scripts/dev-server.mjs` makes BOTH choices available whenever it can, and tells the
 * Worker which it could not:
 *
 * - **This Worker's containers** (`local`): `wrangler dev` builds and runs `SessionSandbox` on
 *   local Docker (the build is layer-cached, so an unchanged image is quick). Docker not running →
 *   wrangler starts with `--enable-containers=false` and the Worker gets
 *   `DEV_LOCAL_CONTAINERS=off`, which disables the choice with the reason.
 * - **The remote sandbox host** (`remote`): REAL Cloudflare containers in the deployed sandbox host
 *   Worker (`apps/web/wrangler.sandbox-host.toml`, `launch-sandbox-dev`) through a REMOTE service
 *   binding, `SANDBOX_HOST`. That binding must not be in `wrangler.toml` or `wrangler.staging.toml`
 *   (a deploy would bind production Launch to a development Worker, and the two files must keep one
 *   shape), so the dev server GENERATES a third file: `wrangler.toml` byte for byte plus the
 *   `[[services]]` block, written next to it (wrangler resolves `main`, `[assets]`, the container
 *   image and `.dev.vars` relative to the config file) and git-ignored — regenerated on every start.
 *   It is declared only when wrangler can open it: logged in, and the host deployed. Otherwise the
 *   Worker starts without it and `DEV_SANDBOX_HOST_STATUS` says why (`not_logged_in`,
 *   `not_deployed`, or `off` — `DEV_REMOTE_SANDBOX=0` skips the check).
 *
 * The probes are the impure half and live in the dev server; everything here is pure, so
 * `tests/config/sandbox-host.test.ts` covers the plan for each combination.
 */

/** The generated config, in `apps/web/`. */
export const REMOTE_DEV_CONFIG = 'wrangler.dev-remote.toml'

/** The sandbox host Worker's name (`wrangler.sandbox-host.toml`). */
export const SANDBOX_HOST_SERVICE = 'launch-sandbox-dev'

/** The `DEV_SANDBOX_HOST_STATUS` values (`services/sessions/sandbox-host.ts` reads them). */
export const SANDBOX_HOST_STATUSES = ['ok', 'not_logged_in', 'not_deployed', 'off']

/**
 * Does `.dev.vars` (parsed) still carry the RETIRED `SESSION_SANDBOX_HOST=remote`? The Worker reads
 * it once as the setting's starting value; the dev server only mentions it.
 */
export function legacyRemoteRequested(devVars = {}) {
  return String(devVars.SESSION_SANDBOX_HOST ?? '').trim() === 'remote'
}

/** `wrangler.toml`'s text with the remote binding appended, and a header saying what it is. */
export function remoteDevConfigText(baseToml) {
  return [
    '# GENERATED by apps/web/scripts/dev-server.mjs: wrangler.toml plus the SANDBOX_HOST remote',
    '# service binding at the end, so sessions can run on the remote sandbox host (the',
    '# session_sandbox_host platform setting). Do not edit (it is rewritten on every `pnpm dev`) and',
    '# never deploy it. Git-ignored.',
    '',
    baseToml.trimEnd(),
    '',
    '# ---- development only: the sandbox host (docs/SESSIONS-LOCAL.md § Real containers from a laptop)',
    '[[services]]',
    'binding = "SANDBOX_HOST"',
    `service = "${SANDBOX_HOST_SERVICE}"`,
    'remote = true',
    '',
  ].join('\n')
}

/**
 * What `wrangler dev` runs with, given what the probes found: `docker` (Docker answers) and
 * `remote` (a `SANDBOX_HOST_STATUSES` value). `writeRemoteConfig`: write
 * {@link REMOTE_DEV_CONFIG} and point wrangler at it. `lines`: what to tell the developer.
 */
export function devSandboxPlan({ docker, remote }) {
  const status = SANDBOX_HOST_STATUSES.includes(remote) ? remote : 'not_deployed'
  const writeRemoteConfig = status === 'ok'
  const args = [
    ...(writeRemoteConfig ? ['-c', REMOTE_DEV_CONFIG] : []),
    ...(docker ? [] : ['--enable-containers=false']),
    '--var',
    `DEV_LOCAL_CONTAINERS:${docker ? 'on' : 'off'}`,
    '--var',
    `DEV_SANDBOX_HOST_STATUS:${status}`,
  ]
  const lines = [
    docker
      ? "sessions: this Worker's containers (local Docker) available"
      : "sessions: Docker is not running — this Worker's containers are unavailable until you start Docker and restart pnpm dev",
    status === 'ok'
      ? `sessions: remote sandbox host (${SANDBOX_HOST_SERVICE}) available`
      : status === 'off'
        ? 'sessions: remote sandbox host skipped (DEV_REMOTE_SANDBOX=0)'
        : status === 'not_logged_in'
          ? 'sessions: remote sandbox host unavailable — run `wrangler login` and restart pnpm dev'
          : `sessions: remote sandbox host unavailable — ${SANDBOX_HOST_SERVICE} is not deployed in your account (docs/DEPLOY.md § The sandbox host)`,
  ]
  return { args, writeRemoteConfig, lines, status }
}

/** Read `wrangler whoami`'s output: is anyone logged in? */
export function whoamiLoggedIn(output) {
  const text = String(output ?? '')
  return /You are logged in/i.test(text) && !/not authenticated/i.test(text)
}
